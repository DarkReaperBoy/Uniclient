class StickerPackViewer extends StatefulWidget {
  final CachedMessage message;
  final EngineService engine;

  const StickerPackViewer({super.key, required this.message, required this.engine});

  static void show(BuildContext context, CachedMessage message) {
    final engine = context.read<EngineService>();
    showModalBottomSheet(
      context: context,
      isScrollControlled: true,
      backgroundColor: Colors.transparent,
      builder: (_) => StickerPackViewer(message: message, engine: engine),
    );
  }

  @override
  State<StickerPackViewer> createState() => _StickerPackViewerState();
}

class _StickerPackViewerState extends State<StickerPackViewer> {
  StickerSetInfo? _setInfo;
  bool _loading = true;
  String? _error;

  @override
  void initState() {
    super.initState();
    _fetchStickerSet();
  }

  Future<void> _fetchStickerSet() async {
    final engine = widget.engine;
    final msg = widget.message;
    try {
      final info = await engine.getStickerSetInfo(
        msg.accountId,
        shortName: msg.stickerSetShortName,
        setId: msg.stickerSetId,
        accessHash: msg.stickerSetAccessHash,
      );
      if (mounted) {
        setState(() {
          _setInfo = info;
          _loading = false;
          if (info == null) _error = 'Sticker set not found';
        });
      }
    } catch (e) {
      if (mounted) {
        setState(() {
          _loading = false;
          _error = e.toString();
        });
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final isDark = theme.brightness == Brightness.dark;
    final bgColor = isDark ? const Color(0xFF1E2C3A) : Colors.white;
    final textColor = isDark ? Colors.white : Colors.black87;

    return DraggableScrollableSheet(
      initialChildSize: 0.6,
      minChildSize: 0.3,
      maxChildSize: 0.9,
      builder: (context, scrollController) {
        return Container(
          decoration: BoxDecoration(
            color: bgColor,
            borderRadius: const BorderRadius.vertical(top: Radius.circular(16)),
          ),
          child: Column(
            children: [
              _buildHandle(),
              _buildHeader(textColor, isDark),
              const Divider(height: 1),
              Expanded(
                child: _loading
                    ? const Center(child: CircularProgressIndicator())
                    : _error != null
                        ? Center(child: Text(_error!, style: TextStyle(color: textColor)))
                        : _buildGrid(scrollController),
              ),
            ],
          ),
        );
      },
    );
  }

  Widget _buildHandle() {
    return Padding(
      padding: const EdgeInsets.only(top: 8, bottom: 4),
      child: Container(
        width: 36,
        height: 4,
        decoration: BoxDecoration(
          color: Colors.grey.withValues(alpha: 0.4),
          borderRadius: BorderRadius.circular(2),
        ),
      ),
    );
  }

  Widget _buildHeader(Color textColor, bool isDark) {
    final info = _setInfo;
    final title = info?.title ?? 'Sticker Pack';
    final count = info?.count ?? 0;
    final installed = info?.installed ?? false;

    return Padding(
      padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
      child: Row(
        children: [
          Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  title,
                  style: TextStyle(
                    fontSize: 16,
                    fontWeight: FontWeight.w600,
                    color: textColor,
                  ),
                ),
                if (count > 0)
                  Text(
                    '$count stickers',
                    style: TextStyle(
                      fontSize: 13,
                      color: textColor.withValues(alpha: 0.6),
                    ),
                  ),
              ],
            ),
          ),
          if (info != null && !_loading)
            TextButton(
              onPressed: null,
              style: TextButton.styleFrom(
                backgroundColor: installed
                    ? (isDark ? const Color(0xFF2B5278) : const Color(0xFFE3F2FD))
                    : const Color(0xFF40A7E3),
                foregroundColor: installed ? textColor : Colors.white,
                padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 8),
                shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(8)),
              ),
              child: Text(installed ? 'Added' : 'Add Stickers'),
            ),
        ],
      ),
    );
  }

  Widget _buildGrid(ScrollController scrollController) {
    final stickers = _setInfo?.stickers ?? [];
    if (stickers.isEmpty) {
      return const Center(child: Text('No stickers'));
    }

    return GridView.builder(
      controller: scrollController,
      padding: const EdgeInsets.all(8),
      gridDelegate: const SliverGridDelegateWithFixedCrossAxisCount(
        crossAxisCount: 5,
        mainAxisSpacing: 4,
        crossAxisSpacing: 4,
      ),
      itemCount: stickers.length,
      itemBuilder: (context, index) {
        final sticker = stickers[index];
        return _StickerTile(sticker: sticker);
      },
    );
  }
}

class _StickerTile extends StatelessWidget {
  final StickerInfoItem sticker;

  const _StickerTile({required this.sticker});

  @override
  Widget build(BuildContext context) {
    Widget child;
    if (sticker.thumbB64.isNotEmpty) {
      try {
        final bytes = _decodeStrippedThumb(sticker.thumbB64);
        child = Image.memory(
          bytes,
          fit: BoxFit.contain,
          gaplessPlayback: true,
        );
      } catch (_) {
        child = _emojiPlaceholder();
      }
    } else {
      child = _emojiPlaceholder();
    }

    return TelegramTooltip(
      message: sticker.emoji,
      child: Padding(
        padding: const EdgeInsets.all(4),
        child: child,
      ),
    );
  }

  Widget _emojiPlaceholder() {
    return Center(
      child: Text(
        sticker.emoji.isNotEmpty ? sticker.emoji : '?',
        style: const TextStyle(fontSize: 28),
      ),
    );
  }

  static Uint8List _decodeStrippedThumb(String b64) {
    final stripped = base64Decode(b64);
    if (stripped.length < 3 || stripped[0] != 0x01) {
      return stripped;
    }
    final w = stripped[1];
    final h = stripped[2];
    final header = _jpegHeader(w, h);
    final footer = _jpegFooter;
    final buf = Uint8List(header.length + stripped.length - 3 + footer.length);
    buf.setAll(0, header);
    buf.setAll(header.length, stripped.sublist(3));
    buf.setAll(header.length + stripped.length - 3, footer);
    return buf;
  }

